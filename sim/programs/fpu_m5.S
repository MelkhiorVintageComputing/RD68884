| RD68884 -- the M5 system test: the arithmetic, on a real MC68020 (RD68021).
| Self-checking; sim/tb/sys_tb.sv waits for the results block and reports it.
|
|   RES+$00  'DONE'            RES+$04  checks made      RES+$08  checks failed
|   RES+$0C  first failing check, RES+$10  an unexpected exception's vector
|   RES+$18  first failing value, RES+$1C  what was wanted
|
| The vectors are generated by sim/programs/gen_fpu_m5.py from the golden
| model (tools/model/arith.py). Each one is
|
|       lea     V, %a2
|       bsr     pre             FP1 <- dst, FP2 <- src as X, FPCR, FPSR <- 0
|       <one instruction>       on FP1, with FP2 or 12(%a2) or (%a3)
|       bsr     post            FP1, the output buffer, FPSR, the vector taken
|
| and its record V:
|
|   +0  dst (X)      +12 src (X, or the format's image at +12)
|   +24 FPCR         +28 FP1 wanted (X, as FMOVE.X with FPCR = 0 writes it)
|   +40 the output buffer wanted     +52 FPSR wanted    +56 vector wanted
|
| FPU = MC68881UM_split, UM = MC68020UM_split.

        .equ    STACK_TOP, 0x0000F000
        .equ    RES,       0x0000C000
        .equ    OBUF,      0x0000C100       | the output buffer, 12 bytes
        .equ    FBUF,      0x0000C110       | FP1's dump, 12 bytes
        .equ    PATTERN,   0xA5C3E187

        .section .vectors, "a"
        .long   STACK_TOP, _start
        .rept   46
        .long   unexpected                  | 2-47
        .endr
        .rept   7
        .long   h_arith                     | 48-54: the FPU's exceptions
        .endr
        .rept   201
        .long   unexpected                  | 55-255
        .endr

        .text
        .globl  _start
_start:
        andi    #0x00, %ccr
        move.l  #STACK_TOP, %sp
        lea     RES, %a0
        moveq   #31, %d0
1:      clr.l   (%a0)+
        dbf     %d0, 1b
        lea     OBUF, %a3

        .include "fpu_m5_vec.S"

        move.l  #0x444F4E45, RES
        .globl  _done
_done:  bra     _done

| pre: a2 is the record.
pre:    fmove.l #0, %fpcr
        fmove.x (%a2), %fp1
        fmove.x 12(%a2), %fp2
        move.l  #PATTERN, (%a3)
        move.l  #PATTERN, 4(%a3)
        move.l  #PATTERN, 8(%a3)
        fmove.l 24(%a2), %fpcr
        fmove.l #0, %fpsr
        moveq   #0, %d7
        rts

| post: the FPSR as the instruction left it; FNOP takes a pending exception
| (FPU 6.1, the handler records its vector); then the results.
post:   fmove.l %fpsr, %d2
        fnop
        fmove.l #0, %fpcr
        fmove.x %fp1, FBUF
        lea     FBUF, %a1
        lea     28(%a2), %a4
        moveq   #2, %d6
1:      move.l  (%a1)+, %d0
        move.l  (%a4)+, %d1
        bsr     check
        dbf     %d6, 1b
        move.l  %a3, %a1
        moveq   #2, %d6
2:      move.l  (%a1)+, %d0
        move.l  (%a4)+, %d1
        bsr     check
        dbf     %d6, 2b
        move.l  %d2, %d0
        move.l  (%a4)+, %d1
        bsr     check
        move.l  %d7, %d0
        move.l  (%a4)+, %d1
        bsr     check
        rts

| check: d0 is what was found, d1 what was wanted.
check:  addq.l  #1, RES+4
        cmp.l   %d1, %d0
        beq.s   1f
        addq.l  #1, RES+8
        tst.l   RES+12
        bne.s   1f
        move.l  RES+4, RES+12
        move.l  %d0, RES+0x18
        move.l  %d1, RES+0x1C
1:      rts

| The arithmetic exceptions, pre- or mid-instruction (FPU 6.1, UM 7.4): note
| the vector and return; a pre-instruction exception's RTE runs the
| instruction again, now with nothing pending.
h_arith:
        move.w  6(%sp), %d7
        andi.l  #0x0FFF, %d7
        lsr.l   #2, %d7
        rte

unexpected:
        move.w  6(%sp), %d0
        andi.l  #0x0FFF, %d0
        lsr.l   #2, %d0
        move.l  %d0, RES+0x10
        move.l  #0x444F4E45, RES
        bra     _done
